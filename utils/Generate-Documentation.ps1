Using module Alt3.Docusaurus.Powershell
Using module PlatyPS

Set-StrictMode -Version Latest;

# -----------------------------------------------------------------------------
# Use below settings to manipulate the rendered MDX files
# -----------------------------------------------------------------------------
$DocsFolder = Resolve-Path "$PSScriptRoot/../docs/docs";
$DocusaurusOptions = @{
    DocsFolder      = $DocsFolder
    EditUrl         = "null"
    Exclude         = @()
    MetaDescription = 'Help page for the "%1" command'
    MetaKeywords    = @('PowerShell', 'Help', 'Documentation')
}

# Alt3 caches intermediate markdown here.
$TempFolder = Join-Path -Path ([System.IO.Path]::GetTempPath()) -ChildPath 'Alt3.Docusaurus.Powershell';
if (Test-Path -Path $TempFolder) {
    Remove-Item -Path $TempFolder -Recurse -Force;
}

# -----------------------------------------------------------------------------
# Script modules: comment-based help via Alt3
# -----------------------------------------------------------------------------
$Slash = [System.IO.Path]::DirectorySeparatorChar;
$Modules = Get-ChildItem -Path "$PSScriptRoot/../src/" -Include '*.psm1' -File -Recurse |
    Where-Object { $_.FullName -notlike "*${Slash}Compiler${Slash}*" };
foreach ($Module in $Modules) {
    $ModuleDocusaurusOptions = $DocusaurusOptions.Clone();
    $ModuleDocusaurusOptions.Module = $Module.BaseName;

    $Parents = $Module.DirectoryName.Split("${Slash}src${Slash}")[1];
    $ModuleDocusaurusOptions.SideBar = "module/$Parents/$($Module.BaseName)";

    Write-Output "Generating new MDX files for module: $($Module.BaseName) in $Parents";
    try {
        $Error.clear()

        try {
            Import-Module -Name $Module.FullName -Force -ErrorAction Stop;
        } catch {
            $Errs = $Error.clone();
            Write-Error "Unable to import $($Module.FullName)"
            Write-Error "Possible errors:"
            Write-Output $Errs
            continue
        }

        New-DocusaurusHelp @ModuleDocusaurusOptions;
    } catch {
        Write-Error "Failed to generate MDX files for module: $($Module.BaseName) in $Parents" -ErrorAction Continue;
        Write-Error $_ -ErrorAction Continue;
    } finally {
        Remove-Module -Name $Module.BaseName -Force -ErrorAction SilentlyContinue;
    }
}

# -----------------------------------------------------------------------------
# Binary module: MDX and MAML from C# XML doc comments
# -----------------------------------------------------------------------------
# Regenerates the whole common docs tree, so pages for removed cmdlets do not
# linger. Requires the module and its XML documentation file to be built.
$CommonManifest = Join-Path $PSScriptRoot '../Output/PowerShellModules/AMT.PowerShell.Common/AMT.PowerShell.Common.psd1';
$CommonXmlDoc = Join-Path $PSScriptRoot '../src/AMT.PowerShell.Common/bin/Debug/AMT.PowerShell.Common.xml';
$CommonDocsFolder = Join-Path -Path $DocsFolder -ChildPath 'module/common';
$MamlPath = Join-Path $PSScriptRoot '../src/AMT.PowerShell.Common/Module/en-AU/AMT.PowerShell.Common-help.xml';
if ((Test-Path -Path $CommonManifest -PathType Leaf) -and (Test-Path -Path $CommonXmlDoc -PathType Leaf)) {
    if (Test-Path -Path $CommonDocsFolder) {
        Remove-Item -Path $CommonDocsFolder -Recurse -Force;
    }

    Write-Output 'Generating MDX and MAML for AMT.PowerShell.Common from XML doc comments';
    $GeneratorScript = Join-Path $PSScriptRoot 'generate-module-docs.py';
    try {
        & python3 $GeneratorScript `
            --module $CommonManifest `
            --xml    $CommonXmlDoc `
            --output-mdx  (Join-Path -Path $CommonDocsFolder -ChildPath 'AMT.PowerShell.Common') `
            --output-maml $MamlPath;
        if ($LASTEXITCODE -ne 0) {
            Write-Error 'generate-module-docs.py exited non-zero' -ErrorAction Continue;
        }
    } catch {
        Write-Error "Failed to generate AMT.PowerShell.Common docs: $($_.Exception.Message)" -ErrorAction Continue;
    }
} else {
    Write-Warning "Skipping AMT.PowerShell.Common docs: module or XML doc not found. Run 'dotnet build' first.";
}

# Alt3 writes per-folder sidebar files; the site uses autogenerated sidebars.
Get-ChildItem -Path $DocsFolder -Filter 'docusaurus.sidebar.js' -File -Recurse |
    Remove-Item -Force;

# Normalize generated docs to LF so Git doesn't see spurious changes on Linux
Get-ChildItem -Path $DocsFolder -Recurse -File | ForEach-Object {
    $Content = [System.IO.File]::ReadAllText($_.FullName)
    if ($Content.Contains("`r`n")) {
        $Content = $Content -replace "`r`n", "`n"
        [System.IO.File]::WriteAllText($_.FullName, $Content, [System.Text.UTF8Encoding]::new($false))
    }
}

# -----------------------------------------------------------------------------
# Generate the Sidebar file
# -----------------------------------------------------------------------------
$Sidebar = "$PSScriptRoot/../docs/sidebars.js";
@'
// @ts-check

/** @type {import('@docusaurus/plugin-content-docs').SidebarsConfig} */
const sidebars = {
  ModulesSidebar: [{type: 'autogenerated', dirName: 'module'}],
};

export default sidebars;

'@ | Set-Content -Path $Sidebar -Force;
