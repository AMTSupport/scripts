using System;
using System.IO;
using System.Management.Automation;
using System.Text;

namespace AMT.PowerShell.Common.Commands.Cache;

/// <summary>Retrieve the parsed content of a named cache entry, invoking <c>CreateBlock</c> to populate it when missing or stale.</summary>
/// <remarks>
/// <para>Resolves the cache file path via <see cref="CacheOperations.GetCachePath"/>, then validates
/// the existing file against <c>MaxAge</c>, <c>IsValidBlock</c>, or <c>NoCache</c>.
/// If the file is absent or invalid it is regenerated by calling <c>CreateBlock</c>.</para>
/// <para>Content is written as plain text via <see cref="System.IO.File.WriteAllText"/> unless
/// <c>WriteBlock</c> is supplied, which receives the cache path and raw content object.</para>
/// <para>The cached file is then read and passed to <c>ParseBlock</c> if supplied;
/// otherwise it is parsed with <c>ConvertFrom-Json -AsHashtable</c> and the resulting object
/// is emitted to the pipeline.</para>
/// </remarks>
/// <example>
/// <code>Get-CachedContent -Name 'config' -CreateBlock { Invoke-RestMethod 'https://api/config' | ConvertTo-Json } -MaxAge ([TimeSpan]::FromHours(1))</code>
/// Returns the parsed JSON hashtable, refreshing the cache when it is older than one hour.
/// </example>
[Cmdlet(VerbsCommon.Get, "CachedContent")]
[OutputType(typeof(object))]
public sealed class GetCachedContentCommand : PSCmdlet {
    /// <summary>Unique name that identifies the cache entry and is used to derive the cache file path.</summary>
    [Parameter(Mandatory = true, Position = 0)]
    [ValidateNotNullOrEmpty]
    public string Name { get; set; } = string.Empty;

    /// <summary>Script block invoked to generate content when the cache is missing or stale; should return a JSON string.</summary>
    [Parameter(Mandatory = true)]
    [ValidateNotNull]
    public ScriptBlock CreateBlock { get; set; } = null!;

    /// <summary>Maximum age of the cache file; when exceeded the file is deleted and recreated via <c>CreateBlock</c>.</summary>
    [Parameter]
    public TimeSpan MaxAge { get; set; }

    /// <summary>Optional script block receiving the cache file path and returning a boolean indicating whether the content is still valid.</summary>
    [Parameter]
    public ScriptBlock? IsValidBlock { get; set; }

    /// <summary>Optional script block to parse the raw cache content; defaults to <c>ConvertFrom-Json -AsHashtable</c>.</summary>
    [Parameter]
    public ScriptBlock? ParseBlock { get; set; }

    /// <summary>Optional script block to write content to the cache file; receives the cache path and raw content object as arguments.</summary>
    [Parameter]
    public ScriptBlock? WriteBlock { get; set; }

    /// <summary>When present, bypasses any existing cache and always invokes <c>CreateBlock</c> to regenerate content.</summary>
    [Parameter]
    public SwitchParameter NoCache { get; set; }

    protected override void ProcessRecord() {
        var cachePath = CacheOperations.GetCachePath(Name);
        CacheOperations.EnsureCacheFolder(cachePath);

        if (File.Exists(cachePath)) {
            var shouldDelete = false;

            if (NoCache.IsPresent) {
                shouldDelete = true;
            } else if (MyInvocation.BoundParameters.ContainsKey(nameof(MaxAge))) {
                var age = DateTime.UtcNow - File.GetLastWriteTimeUtc(cachePath);
                if (age > MaxAge) shouldDelete = true;
            } else if (IsValidBlock is not null) {
                var validResult = IsValidBlock.Invoke(cachePath);
                var isValid = validResult.Count > 0 && validResult[0].BaseObject is bool b && b;
                if (!isValid) shouldDelete = true;
            }

            if (shouldDelete) File.Delete(cachePath);
        }

        if (!File.Exists(cachePath)) {
            var contentResults = CreateBlock.Invoke();

            if (WriteBlock is not null) {
                // Preserve raw types (e.g. byte[]); same convention as GetCachedLocationCommand.
                object rawContent;
                if (contentResults.Count == 0) {
                    rawContent = Array.Empty<object>();
                } else if (contentResults.Count == 1) {
                    rawContent = contentResults[0].BaseObject ?? string.Empty;
                } else {
                    var items = new object[contentResults.Count];
                    for (var i = 0; i < contentResults.Count; i++) items[i] = contentResults[i].BaseObject ?? string.Empty;
                    rawContent = items;
                }

                WriteBlock.Invoke(cachePath, rawContent);
            } else {
                var content = contentResults.Count > 0
                    ? contentResults[0].BaseObject?.ToString() ?? string.Empty
                    : string.Empty;
                File.WriteAllText(cachePath, content, Encoding.UTF8);
            }
        }

        var raw = File.ReadAllText(cachePath);

        if (ParseBlock is not null) {
            var parsed = ParseBlock.Invoke(raw);
            if (parsed.Count > 0) WriteObject(parsed[0].BaseObject, enumerateCollection: false);
            return;
        }

        // Default: parse as JSON hashtable via PowerShell's ConvertFrom-Json.
        var jsonResults = this.InvokeCommand.InvokeScript(
            "ConvertFrom-Json -InputObject $args[0] -AsHashtable",
            raw);

        if (jsonResults.Count > 0) WriteObject(jsonResults[0].BaseObject, enumerateCollection: false);
    }
}
